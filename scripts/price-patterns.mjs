/**
 * ТЗ §1 и §15: никаких цен ни на одном языке — ни цифр с валютой, ни «от …», ни тарифов.
 * Общий список для скрипта проверки сборки и для юнит-тестов словарей.
 */
export const PRICE_PATTERNS = [
  { name: 'символ валюты', re: /[€$₽£₴¥]/ },
  { name: 'код валюты', re: /\b(EUR|USD|MDL|UAH|RUB|PLN|GBP)\b/i },
  { name: 'название валюты', re: /(евро|доллар|долар|гривн|грн\b|руб\.|рубл|\bлей\b|\bлеев\b|\blei\b|euro\b|dollar)/i },
  { name: 'слово о цене', re: /(цена|цены|цену|стоимост|прайс|тариф|ціна|ціни|ціну|вартіст|\bprice|\bpricing\b|\bcost\b|\bfee\b|\btariff)/i },
  { name: '«от/від/from» + число', re: /(^|[^\p{L}])(от|від|from)\s*\d/iu },
  { name: 'число + валюта', re: /\d[\d\s.,]*\s*(€|\$|eur|usd|лей|lei|грн|₽|руб)/i },
]

/** Фразы, которые ТЗ запрещает прямо (§4, §8, §10, §12). */
export const FORBIDDEN_PHRASES = [
  'Смотреть портфолио',
  'Избранные проекты',
  'I’m a Solda',
  "I'm a Solda",
  "I'm a soldier",
  'онлайн по всему миру',
  'Дополнительная услуга. Объём работ и стоимость',
  '1 Reels + 10 фото',
  'Отправить',
  'Ваше имя',
]

export function findPrices(text) {
  return PRICE_PATTERNS.filter((p) => p.re.test(text)).map((p) => p.name)
}
